window.toggleRawMarkdown = function() {
  const rawView = document.getElementById('raw-markdown');
  const btn = document.querySelector('.raw-toggle-btn');
  if (!rawView || !btn) return;

  const isHidden = rawView.hidden;
  rawView.hidden = !isHidden;
  btn.setAttribute('aria-expanded', String(isHidden));
  btn.textContent = isHidden ? 'Markdown を閉じる' : 'Markdown を表示';
};
